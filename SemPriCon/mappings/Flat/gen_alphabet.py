#!/usr/bin/env python3
"""gen_alphabet.py — writes the per-language alphabet headers for the table build (-DALPHABET_TABLE -DALPHABET_HEADER='"alphabet_<lang>.h"').

The alphabet is the set of code points the language's WRITING needs, sorted by code point; a character's digit is its 1-based rank in that list (0 = not in the
alphabet).  The Horner base is the alphabet size.  This is the eb28ce8 construction (95 printable ASCII characters, base 95) with the alphabet changed per language.
  zh  every assigned CJK ideograph in the engine's Han ranges (unicodedata 15.0, category Lo): the whole Han repertoire, no Latin, no kana, no punctuation.
  fi  ' a-z å ä ö š ž    (Finnish; š and ž occur in loanwords and names)
  un  ' a-z + every Han ideograph (the zh set): the union alphabet for the mixed zh+en bins.
English and Indonesian write in ASCII and use the unmodified ASCII-95 build (-DALPHABET_ASCII95), as before.
"""
import os, unicodedata as ud
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "PtolC_unicode")
HAN = [(0x3400, 0x4DBF), (0x4E00, 0x9FFF), (0xF900, 0xFAFF), (0x20000, 0x2A6DF), (0x2A700, 0x2EBEF), (0x30000, 0x323AF)]   # = U_HAN in unicode_tables.h

def zh():
    return [cp for lo, hi in HAN for cp in range(lo, hi + 1) if ud.category(chr(cp)) == "Lo"]

def fi():
    return sorted([0x27] + list(range(0x61, 0x7B)) + [ord(c) for c in "åäöšž"])

def union():
    return fi_ascii() + zh()

def fi_ascii():
    return [0x27] + list(range(0x61, 0x7B))

def write(name, cps):
    cps = sorted(set(cps))
    with open(os.path.join(OUT, f"alphabet_{name}.h"), "w") as f:
        f.write(f"/* alphabet_{name}.h — GENERATED by tools/gen_alphabet.py (unicodedata {ud.unidata_version}). Do not edit. */\n")
        f.write(f"#define ALPHA_NAME \"{name}\"\n#define ALPHA_N {len(cps)}\nstatic const uint32_t ALPHA[ALPHA_N] = {{\n")
        for i in range(0, len(cps), 12):
            f.write("  " + ", ".join(f"0x{c:X}" for c in cps[i:i + 12]) + ",\n")
        f.write("};\n")
    print(name, len(cps), "characters; first", hex(cps[0]), "last", hex(cps[-1]))

if __name__ == "__main__":
    write("zh", zh()); write("fi", fi()); write("un", union())
