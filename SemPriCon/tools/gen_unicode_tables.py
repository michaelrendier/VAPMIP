#!/usr/bin/env python3
"""gen_unicode_tables.py — writes src/PtolC_unicode/unicode_tables.h from Python's `unicodedata` (the Unicode version is recorded in the header).

Tables (all sorted, searched by binary search in unicode.c):
  U_WORD   code point ranges whose General_Category is L* (letters) or M* (marks)
  U_HAN    CJK ideograph blocks (each character is its own token: no segmenter)
  U_LATIN  code point ranges of Latin-script letters
  U_VOWEL  lower-case Latin vowels, including every letter whose canonical decomposition starts with a, e, i, o, u or y, plus æ œ ø
  U_LOWER  simple lower-case mappings (cp -> cp) where str.lower() of the single character is a single character
"""
import os, sys, unicodedata as ud
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "PtolC_unicode", "unicode_tables.h")

def ranges(pred):
    out, start, prev = [], None, None
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF: ok = False
        else: ok = pred(chr(cp))
        if ok and start is None: start = cp
        if not ok and start is not None: out.append((start, cp - 1)); start = None
    if start is not None: out.append((start, 0x10FFFF))
    return out

word = ranges(lambda c: ud.category(c)[0] in "LM")
latin = ranges(lambda c: ud.category(c)[0] == "L" and ud.name(c, "").startswith("LATIN"))
HAN = [(0x3400, 0x4DBF), (0x4E00, 0x9FFF), (0xF900, 0xFAFF), (0x20000, 0x2A6DF), (0x2A700, 0x2EBEF), (0x30000, 0x323AF)]
vowels = sorted(cp for r in latin for cp in range(r[0], r[1] + 1)
                if ud.category(chr(cp)) == "Ll" and (ud.normalize("NFD", chr(cp))[0] in "aeiouy" or chr(cp) in "æœø"))
lower = [(cp, ord(chr(cp).lower())) for cp in range(0x110000) if not 0xD800 <= cp <= 0xDFFF and len(chr(cp).lower()) == 1 and ord(chr(cp).lower()) != cp]

def arr2(name, rs): return f"static const uint32_t {name}[][2] = {{\n" + ",\n".join("    {0x%X, 0x%X}" % r for r in rs) + f"\n}};\n#define {name}_N {len(rs)}\n"
with open(OUT, "w") as f:
    f.write(f"/* unicode_tables.h — GENERATED by tools/gen_unicode_tables.py from Python {sys.version.split()[0]} unicodedata. Do not edit. */\n")
    f.write(f'#define UNICODE_DATA_VERSION "{ud.unidata_version}"\n')
    f.write(arr2("U_WORD", word)); f.write(arr2("U_HAN", HAN)); f.write(arr2("U_LATIN", latin))
    f.write("static const uint32_t U_VOWEL[] = {\n" + ",\n".join("    0x%X" % c for c in vowels) + f"\n}};\n#define U_VOWEL_N {len(vowels)}\n")
    f.write(arr2("U_LOWER", lower))
print("unicode", ud.unidata_version, "word ranges", len(word), "latin", len(latin), "vowels", len(vowels), "lower", len(lower))
