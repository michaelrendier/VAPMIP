"""ring_circle_battery.py — is the sedenion a set of circle-modifying operators?  (the Ring–Circle battery)

Hypothesis (Cody, 2026-10-20): ring theory has hyperspherical representations — adding an axis across a ring and rotating in place about it — so ring theory
may be the clearest reading of both Universal Native Space (UNS) and 0_RB, and the sedenion would be a set of operators each of which deforms, partitions,
permutes or scales a circle.  The battery tests that on the repo's own product (SedenionSpectralRelativity/emerger_spectrum.py cd_mul).  Every table is exact
(integer structure constants; ranks by SVD on integer matrices, tolerance 1e-9).  Label for every result below: :CALCULATED.

    python3 ring_circle_battery.py                 # all tests, writes results.json
"""
