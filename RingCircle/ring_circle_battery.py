DIM = 16
def dprint(name, value):
    if os.environ.get("PTOL_DPRINT", "0") not in ("", "0"): print(f"[dp] {name} = {value!r}", flush=True)

# structure constants: e_i e_j = s e_k   (T[i,j,k] = s)
T = np.zeros((DIM, DIM, DIM), dtype=np.int64)
for i in range(DIM):
    for j in range(DIM):
        v = cd_mul(_e(i), _e(j)); k = [n for n, c in enumerate(v) if c != 0]; assert len(k) == 1 and abs(v[k[0]]) == 1
        T[i, j, k[0]] = int(v[k[0]])
        assert k[0] == i ^ j                       # the product of two basis slots is the XOR slot
def mul(x, y): return np.einsum("i,j,ijk->k", x, y, T)
def L(a): return np.einsum("i,ijk->kj", a, T).astype(float)          # L_a x = a x
def R(a): return np.einsum("j,ijk->ki", a, T).astype(float)          # R_a x = x a
def unit(k): v = np.zeros(DIM); v[k] = 1.0; return v
I = np.eye(DIM)
LK = {k: L(unit(k)) for k in range(DIM)}; RK = {k: R(unit(k)) for k in range(DIM)}
res = {}

# ── RC-1  every slot is a circle ────────────────────────────────────────────
c1 = {"L_k_squared_is_minus_I": [], "L_k_skew_orthogonal": [], "R_k_squared_is_minus_I": [], "span_e0_ek_closed_copy_of_C": []}
for k in range(1, DIM):
    c1["L_k_squared_is_minus_I"].append(bool(np.allclose(LK[k] @ LK[k], -I)))
    c1["L_k_skew_orthogonal"].append(bool(np.allclose(LK[k].T, -LK[k]) and np.allclose(LK[k] @ LK[k].T, I)))
    c1["R_k_squared_is_minus_I"].append(bool(np.allclose(RK[k] @ RK[k], -I)))
    c1["span_e0_ek_closed_copy_of_C"].append(bool(np.array_equal(T[k, k], -unit(0).astype(int))))
res["RC1_slots_are_circles"] = {k: sum(v) for k, v in c1.items()}; res["RC1_slots_are_circles"]["of"] = 15
dprint("RC1", res["RC1_slots_are_circles"])

# ── RC-2  how two circles meet: the anticommutator of their rotation generators ──
# Clifford-compatible (A_ij = L_i L_j + L_j L_i = 0): the two axes are perpendicular and each rotates the other in place, as i and j do in H.
A = np.zeros((DIM, DIM)); Cm = np.zeros((DIM, DIM))
for i in range(1, DIM):
    for j in range(1, DIM):
        if i != j:
            A[i, j] = np.linalg.norm(LK[i] @ LK[j] + LK[j] @ LK[i]); Cm[i, j] = np.linalg.norm(LK[i] @ LK[j] - LK[j] @ LK[i])
pairs = [(i, j) for i in range(1, DIM) for j in range(i + 1, DIM)]
zero_pairs = [p for p in pairs if A[p] < 1e-9]; bad_pairs = [p for p in pairs if A[p] >= 1e-9]
inside_O = [p for p in pairs if p[1] < 8]
res["RC2_pairs"] = {"pairs": len(pairs), "anticommuting (Clifford-compatible)": len(zero_pairs), "deforming (anticommutator nonzero)": len(bad_pairs),
                    "pairs inside the octonion slots 1..7": len(inside_O), "of_those_anticommuting": sum(1 for p in inside_O if A[p] < 1e-9),
                    "anticommutator_norm_values": sorted({round(float(A[p]), 6) for p in bad_pairs}),
                    "deforming_pairs_with_both_slots_under_8": sum(1 for p in bad_pairs if p[1] < 8)}
res["RC2_table_anticommutator_norm"] = [[round(float(A[i, j]), 4) for j in range(1, DIM)] for i in range(1, DIM)]
dprint("RC2", res["RC2_pairs"])
# which deforming pairs: classify by the XOR slot and by whether the third slot (i^j) is also deforming with each
res["RC2_deforming_pairs"] = bad_pairs

# ── RC-3  how few operators generate the operator ring ──────────────────────
def alg_dim(mats, n=DIM):
    """dimension of the associative algebra with 1 generated by mats (square n×n real matrices): closure by words, orthonormal basis grown by Gram–Schmidt"""
    Id = np.eye(n); Q = [Id.flatten() / np.linalg.norm(Id)]; words = [Id]
    while True:
        added = []
        for w in words:
            for g in mats:
                m = g @ w; v = m.flatten(); Qm = np.array(Q)
                r = v - Qm.T @ (Qm @ v); r = r - Qm.T @ (Qm @ r)
                if np.linalg.norm(r) > 1e-9 * max(1.0, np.linalg.norm(v)):
                    Q.append(r / np.linalg.norm(r)); added.append(m)
        if not added: break
        words = added
    return len(Q)
gens = {"{1}": [1], "{1,2}": [1, 2], "{1,2,4}": [1, 2, 4], "{1,2,4,8}": [1, 2, 4, 8], "{1,2,4,8} + R": None, "all 15 L_k": list(range(1, 16)), "all 15 L_k + R_k": None}
rc3 = {}
for name, g in gens.items():
    if g is not None: rc3[name] = alg_dim([LK[k] for k in g])
rc3["{1,2,4,8} L and R"] = alg_dim([LK[k] for k in (1, 2, 4, 8)] + [RK[k] for k in (1, 2, 4, 8)])
rc3["all 15 L_k and R_k"] = alg_dim([LK[k] for k in range(1, 16)] + [RK[k] for k in range(1, 16)])
# octonion block for comparison: L_1..L_7 restricted to the 8-dim algebra
def L8(k):
    v = np.zeros(8); 
    return LK[k][:8, :8]
rc3["octonion (8-dim) {1,2,4}"] = None
alg_dim_k = lambda mats, n: alg_dim(mats, n)
rc3["octonion (8-dim) {1,2,4}"] = alg_dim_k([LK[k][:8, :8] for k in (1, 2, 4)], 8)
rc3["octonion (8-dim) all 7"] = alg_dim_k([LK[k][:8, :8] for k in range(1, 8)], 8)
rc3["quaternion (4-dim) {1,2}"] = alg_dim_k([LK[k][:4, :4] for k in (1, 2)], 4)
rc3["complex (2-dim) {1}"] = alg_dim_k([LK[1][:2, :2]], 2)
res["RC3_dimension_of_generated_operator_ring"] = rc3
dprint("RC3", rc3)
# minimal generating subsets of the 15 L_k (against the full-ring dimension) — run on its own below (RC3b), it is the slow step
res["RC3_pair_dimensions"] = {"{1,9} (anticommuting)": alg_dim([LK[1], LK[9]]), "{1,10} (deforming)": alg_dim([LK[1], LK[10]]),
                              "{1,2,10}": alg_dim([LK[1], LK[2], LK[10]]), "{1,2,4,8}": alg_dim([LK[k] for k in (1, 2, 4, 8)])}
dprint("RC3 pairs", res["RC3_pair_dimensions"])

# ── Lie-closure: the circle operators as a Lie algebra; the orbit of e0 is the hypersphere ────────────────────────────
def lie_closure(mats, n=DIM):
    Q = []; B = []
    def add(m):
        v = m.flatten(); 
        if Q:
            Qm = np.array(Q); v2 = v - Qm.T @ (Qm @ v); v2 = v2 - Qm.T @ (Qm @ v2)
        else: v2 = v
        if np.linalg.norm(v2) > 1e-9 * max(1.0, np.linalg.norm(v)): Q.append(v2 / np.linalg.norm(v2)); B.append(m); return True
        return False
    for m in mats: add(m)
    changed = True
    while changed:
        changed = False
        for a in list(B):
            for g in mats:
                if add(a @ g - g @ a): changed = True
    return B
def orbit_dim(B, v): 
    return int(np.linalg.matrix_rank(np.array([b @ v for b in B]), tol=1e-9)) if B else 0
rc_lie = {}
for name, g in {"{1}": [1], "{1,2}": [1, 2], "{1,2,4}": [1, 2, 4], "{1,2,4,8}": [1, 2, 4, 8], "{1,9}": [1, 9], "{1,10}": [1, 10], "all 15": list(range(1, 16))}.items():
    B = lie_closure([LK[k] for k in g]); rc_lie[name] = {"lie_algebra_dim": len(B), "orbit_of_e0_dim": orbit_dim(B, unit(0))}
res["RC3_lie_closure_and_orbit_of_e0"] = rc_lie
