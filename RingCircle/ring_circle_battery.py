# ── RC-4  bracketings and firing orders of the generator circles: what each slot produces ───────────────────────────
def trees(items):
    if len(items) == 1: yield items[0]; return
    for m in range(1, len(items)):
        for l in trees(items[:m]):
            for r in trees(items[m:]): yield (l, r)
def ev(tree, vecs): return vecs[tree] if isinstance(tree, int) else mul(ev(tree[0], vecs), ev(tree[1], vecs))
def shape(tree): return str(tree) if isinstance(tree, int) else "(" + shape(tree[0]) + shape(tree[1]) + ")"
rc4 = {}
for k in range(1, DIM):
    bits = [b for b in (1, 2, 4, 8) if k & b]; m = len(bits)
    tab = {"slot": k, "generators": bits, "firing_orders": math.factorial(m), "bracketings": len(list(trees(list(range(m))))) if m else 0}
    signs = {1: 0, -1: 0}; by_bracket = {}
    for order in itertools.permutations(range(m)):
        for tr in trees(list(range(m))):
            vecs = {i: unit(bits[order[i]]) for i in range(m)}
            r = ev(tr, vecs); idx = int(np.argmax(np.abs(r))); assert idx == k and abs(abs(r[idx]) - 1) < 1e-12 and np.count_nonzero(r) == 1
            sg = int(round(r[idx])); signs[sg] += 1
            parity = sum(1 for a in range(m) for b2 in range(a + 1, m) if order[a] > order[b2]) % 2
            by_bracket.setdefault(shape(tr), []).append(sg * (-1) ** parity)
    tab["sign_counts"] = {"+": signs[1], "-": signs[-1]}
    # for each bracketing, is sign = c·(−1)^(order parity) with one constant c? (then the firing order only enters through parity)
    tab["bracketing_constant_c"] = {b: (sorted(set(v))[0] if len(set(v)) == 1 else "order-dependent beyond parity") for b, v in by_bracket.items()}
    rc4[k] = tab
res["RC4_generator_products_per_slot"] = rc4
dprint("RC4", {k: (v["sign_counts"], v["bracketing_constant_c"]) for k, v in rc4.items() if len(v["generators"]) >= 3})

# ── RC-5  rotating in place: conjugation by a circle, both bracketings ───────────────────────────────────────────────
conj = lambda u: u * np.array([1] + [-1] * (DIM - 1))
rc5 = {"ordered_pairs": 0, "exact_in_place_rotation_both_bracketings": 0, "exact_rotation_left_bracketing_only": 0, "exact_rotation_right_bracketing_only": 0, "neither": 0}
bad_examples = []
for k in range(1, DIM):
    for j in range(DIM):
        if j == k: continue
        rc5["ordered_pairs"] += 1; okL = okR = True
        for th in (0.3, 0.9, 1.4):
            u = math.cos(th) * unit(0) + math.sin(th) * unit(k); ui = conj(u); x = unit(j)
            pL = mul(mul(u, x), ui); pR = mul(u, mul(x, ui))
            # exact in-place rotation: result in span(e_j, e_j e_k), unit norm, angle 2θ about the axis e_k
            xe = mul(x, unit(k)); tgt = math.cos(2 * th) * x - math.sin(2 * th) * xe
            okL &= bool(np.allclose(pL, tgt, atol=1e-9)); okR &= bool(np.allclose(pR, tgt, atol=1e-9))
        if okL and okR: rc5["exact_in_place_rotation_both_bracketings"] += 1
        elif okL: rc5["exact_rotation_left_bracketing_only"] += 1
        elif okR: rc5["exact_rotation_right_bracketing_only"] += 1
        else:
            rc5["neither"] += 1
            if len(bad_examples) < 8: bad_examples.append((k, j))
res["RC5_conjugation_by_circle_k_of_slot_j (j=0 included)"] = rc5; res["RC5_examples_of_neither"] = bad_examples
dprint("RC5", rc5)
# which ordered pairs (k,j>0) fail, against the 42 deforming (Assessor) pairs
fail_pairs = set()
for k in range(1, DIM):
    for j in range(1, DIM):
        if j == k: continue
        ok = True
        for th in (0.3, 0.9):
            u = math.cos(th) * unit(0) + math.sin(th) * unit(k); ui = conj(u); x = unit(j)
            tgt = math.cos(2 * th) * x - math.sin(2 * th) * mul(x, unit(k))
            ok &= bool(np.allclose(mul(mul(u, x), ui), tgt, atol=1e-9)) and bool(np.allclose(mul(u, mul(x, ui)), tgt, atol=1e-9))
        if not ok: fail_pairs.add(tuple(sorted((k, j))))
res["RC5_pairs_where_in_place_rotation_fails"] = sorted(fail_pairs)
res["RC5_failing_pairs_equal_the_42_deforming_pairs"] = (sorted(fail_pairs) == sorted(bad_pairs))
dprint("RC5 fail=42 deforming", res["RC5_failing_pairs_equal_the_42_deforming_pairs"])

# ── RC-6  where composing circles stops being a pure rotation (norm) ────────────────────────────────────────────────
rng = np.random.default_rng(7)
def circ_el(k, th): return math.cos(th) * unit(0) + math.sin(th) * unit(k)
worst_two = 0.0
for i in range(1, DIM):
    for j in range(1, DIM):
        if i != j:
            for _ in range(4):
                a, b = rng.uniform(0, 2 * math.pi, 2); worst_two = max(worst_two, abs(np.linalg.norm(mul(circ_el(i, a), circ_el(j, b))) - 1))
