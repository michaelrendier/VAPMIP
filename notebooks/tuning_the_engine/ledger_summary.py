#!/usr/bin/env python3
"""ledger_summary.py — collect every notebook's final ledger into FINDINGS.md.

Reads the executed phase_*.ipynb files (no re-execution) and writes a table of PASS/FAIL/PROSE/SKIP per phase,
followed by every FAIL with its detail. A FAIL is a claim on the wiki page that did not reproduce against the
live repo; it is a result, not an error in the notebook (cell errors are counted separately)."""
import json, os, re, glob, sys
HERE = os.path.dirname(os.path.abspath(__file__))

def key(p):
    n = re.search(r"phase_(\w+)\.ipynb", p).group(1)
    m = re.match(r"(\d+)(\w*)", n); return (int(m.group(1)), m.group(2))

rows, fails = [], {}
for p in sorted(glob.glob(os.path.join(HERE, "phase_*.ipynb")), key=key):
    nb = json.load(open(p, encoding="utf-8"))
    title = nb["cells"][0]["source"]; title = "".join(title).splitlines()[0].lstrip("# ").strip()
    led = ""
    for o in nb["cells"][-1].get("outputs", []):
        if o.get("output_type") == "stream": led += "".join(o["text"])
    cnt = {k: 0 for k in ("PASS", "FAIL", "PROSE", "SKIP")}
    cur = None; items = []
    for l in led.splitlines():
        m = re.match(r"\s+\[(PASS |FAIL |PROSE|SKIP )\]\s*(.*)", l)
        if m:
            cur = [m.group(1).strip(), m.group(2), ""]; items.append(cur); cnt[cur[0]] += 1
        elif cur and l.startswith("          "): cur[2] += l.strip() + " "
    errs = sum(1 for c in nb["cells"] if c["cell_type"] == "code" for o in c.get("outputs", []) if o.get("output_type") == "error")
    n = re.search(r"phase_(\w+)\.ipynb", p).group(1)
    rows.append((n, title, cnt, errs)); fails[n] = [(c, d) for s, c, d in items if s == "FAIL"]

tot = {k: sum(r[2][k] for r in rows) for k in ("PASS", "FAIL", "PROSE", "SKIP")}
out = ["# Tuning the Engine — companion notebooks: ledger summary", "",
       "Generated by `ledger_summary.py` from the executed notebooks. **PASS** = the page's claim reproduced against the live repo; "
       "**FAIL** = it did not (a finding, kept); **PROSE** = stated on the page with no executable counterpart; **SKIP** = has a counterpart that cannot run here.", "",
       f"**{len(rows)} notebooks · {tot['PASS']} PASS · {tot['FAIL']} FAIL · {tot['PROSE']} PROSE · {tot['SKIP']} SKIP · {sum(r[3] for r in rows)} cell errors**", "",
       "| Phase | Title | PASS | FAIL | PROSE | SKIP | cell errors |", "|---|---|---:|---:|---:|---:|---:|"]
for n, t, c, e in rows:
    out.append(f"| [{n}](phase_{n}.ipynb) | {t.split('—', 1)[-1].strip()} | {c['PASS']} | {c['FAIL']} | {c['PROSE']} | {c['SKIP']} | {e} |")
out += ["", "## Every FAIL, by phase", ""]
for n, t, c, e in rows:
    if not fails[n]: continue
    out.append(f"### Phase {n}")
    for claim, det in fails[n]:
        out.append(f"- **{claim}**" + (f"  \n  {det.strip()}" if det.strip() else ""))
    out.append("")
open(os.path.join(HERE, "FINDINGS.md"), "w", encoding="utf-8").write("\n".join(out) + "\n")
print(f"wrote FINDINGS.md: {len(rows)} notebooks, {tot}")
