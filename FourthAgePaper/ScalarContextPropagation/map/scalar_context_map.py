"""scalar_context_map.py (2026-11-21): the exhaustive map of the Scalar Boxkite context hash over WordNet 3.0.
Run from VAPMIP/ with .venv/bin/python FourthAgePaper/ScalarContextPropagation/map/scalar_context_map.py
Writes (beside this file): scalar_context_map.tsv.gz (one row per lemma-in-synset), CLASS_MAP.md (one row per exact
context class), BASIN_MAP.md (the basins), summary.json.

Definitions (all from wordnet_boxkite.py, nothing new):
  vec19       context_vector(synset): compress_count(len(targets)) for each of the 19 relations
  context_code  prod CONTEXT_PRIMES[i]^vec19[i]                    (exact integer)
  context_addr  next_prime(context_code); delta = addr - code
  gamma_radial  tanh(0.5 ln(log_code/LOG_ANCHOR)), None when the vector is all zero
  class       synsets with an identical vec19 (they share one code, one address, one gamma)
Basins, two readings:
  density basin  intervals of gamma between the valleys of its smoothed histogram
  attractor      on the graph whose nodes are the classes and whose edges join classes whose vectors differ by 1 in exactly
                 one coordinate, each class flows to its most populated neighbour while that neighbour is more populated
                 than it is; the class it stops at is its attractor (basin centre).
"""
import sys, os, gzip, json, math, collections
sys.path.insert(0, '.')
import wordnet_boxkite as W
from nltk.corpus import wordnet as wn
HERE = os.path.dirname(os.path.abspath(__file__))
names = W.RELATION_METHODS
POS = {'n': 'noun', 'v': 'verb', 'a': 'adj', 's': 'adj-sat', 'r': 'adv'}

syn = list(wn.all_synsets())
vec = {}
for s in syn: vec[s.name()] = tuple(W.context_vector(s))
classes = collections.defaultdict(list)
for s in syn: classes[vec[s.name()]].append(s)
order = sorted(classes, key=lambda v: (-len(classes[v]), v))
cid = {v: i + 1 for i, v in enumerate(order)}              # class 1 = the biggest
code, addr = {}, {}
for v in order:
    c = 1
    for p, e in zip(W.CONTEXT_PRIMES, v):
        if e: c *= p ** e
    code[v] = c; addr[v] = W.next_prime(c)
gam = {v: W.gamma_radial(list(v)) for v in order}

# density basins of gamma
vals = sorted(g for v in order for g in [gam[v]] * len(classes[v]) if g is not None)
B = 200; lo, hi = -1.0, 1.0; h = [0] * B
for g in vals: h[min(B - 1, int((g - lo) / (hi - lo) * B))] += 1
sm = [sum(h[max(0, i - 2):i + 3]) / len(h[max(0, i - 2):i + 3]) for i in range(B)]
mx = max(sm)
valleys = [lo + (i + .5) * (hi - lo) / B for i in range(1, B - 1) if sm[i] < sm[i - 1] and sm[i] <= sm[i + 1] and sm[i] < 0.6 * mx]
edges = [lo] + valleys + [hi]
def dbasin(g):
    if g is None: return 0
    for k in range(len(edges) - 1):
        if edges[k] <= g < edges[k + 1]: return k + 1
    return len(edges) - 1

# attractor basins on the class graph
V = list(order); idx = {v: i for i, v in enumerate(V)}; pop = {v: len(classes[v]) for v in V}
nbr = collections.defaultdict(list)
byv = set(V)
for v in V:
    for i in range(19):
        for d in (-1, 1):
            w = list(v); w[i] += d
            w = tuple(w)
            if w in byv: nbr[v].append(w)
def attractor(v):
    seen = set()
    while True:
        seen.add(v)
        best = max(nbr[v], key=lambda w: (pop[w], -idx[w]), default=None)
        if best is None or pop[best] <= pop[v] or best in seen: return v
        v = best
att = {v: attractor(v) for v in V}
acls = collections.defaultdict(list)
for v in V: acls[att[v]].append(v)
abasin = {a: i + 1 for i, a in enumerate(sorted(acls, key=lambda a: -sum(pop[v] for v in acls[a])))}
deg = [len(nbr[v]) for v in V]
# connected components of the class graph
comp = {}; ncomp = 0
for v in V:
    if v in comp: continue
    ncomp += 1; st = [v]; comp[v] = ncomp
    while st:
        x = st.pop()
        for y in nbr[x]:
            if y not in comp: comp[y] = ncomp; st.append(y)

# the exhaustive table
n_rows = 0
with gzip.open(os.path.join(HERE, 'scalar_context_map.tsv.gz'), 'wt', encoding='utf-8') as f:
    f.write('lemma\tpos\tsynset\toffset\tclass\tdensity_basin\tattractor_basin\tgamma_radial\tvec19\tcontext_code\tcontext_addr\tdelta\n')
    for s in sorted(syn, key=lambda s: (s.pos(), s.offset())):
        v = vec[s.name()]; g = gam[v]
        row_tail = '\t'.join([str(cid[v]), str(dbasin(g)), str(abasin[att[v]]), '' if g is None else '%.6f' % g, ','.join(map(str, v)),
                              str(code[v]), str(addr[v]), str(addr[v] - code[v])])
        for l in s.lemmas():
            f.write('%s\t%s\t%s\t%08d\t%s\n' % (l.name().lower(), s.pos(), s.name(), s.offset(), row_tail)); n_rows += 1
def desc(v): return ' '.join('%s=%d' % (names[i], e) for i, e in enumerate(v) if e) or '(no relations)'
with open(os.path.join(HERE, 'CLASS_MAP.md'), 'w', encoding='utf-8') as f:
    f.write('# Scalar Boxkite context map: every exact context class of WordNet 3.0\n\n')
    f.write('Generated by `scalar_context_map.py` (2026-11-21). %d synsets, %d exact classes (identical 19-vectors), %d lemma-in-synset rows in `scalar_context_map.tsv.gz`. '
            'One class = one context code = one address = one gamma_radial. Columns: class (1 = most populated), synsets, density basin, attractor basin, gamma_radial, vec19 (non-zero relations), context_code, context_addr, POS mix, three example synsets.\n\n' % (len(syn), len(V), n_rows))
    f.write('| class | synsets | dens | attr | gamma | vector | context_code | context_addr | pos | examples |\n|---|---|---|---|---|---|---|---|---|---|\n')
    for v in order:
        g = gam[v]; m = classes[v]; pc = collections.Counter(POS[s.pos()] for s in m)
        f.write('| %d | %d | %d | %d | %s | %s | %d | %d | %s | %s |\n' % (cid[v], len(m), dbasin(g), abasin[att[v]], '' if g is None else '%.4f' % g, desc(v), code[v], addr[v],
                ', '.join('%s %d' % kv for kv in pc.most_common()), ', '.join(s.name() for s in m[:3])))
with open(os.path.join(HERE, 'BASIN_MAP.md'), 'w', encoding='utf-8') as f:
    f.write('# Scalar Boxkite context basins of WordNet 3.0\n\nGenerated by `scalar_context_map.py` (2026-11-21).\n\n')
    f.write('## Reading 1: density basins of gamma_radial\nValleys of the smoothed histogram (200 bins on [-1,1], valley below 60%% of the peak): %s\n\n' % ', '.join('%.3f' % x for x in valleys))
    f.write('| basin | gamma from | to | synsets | classes | mean depth | dominant class | pos mix |\n|---|---|---|---|---|---|---|---|\n')
    for k in range(1, len(edges)):
        mem = [(v, s) for v in order if gam[v] is not None and dbasin(gam[v]) == k for s in classes[v]]
        if not mem: continue
        cs = collections.Counter(v for v, _ in mem); dom = cs.most_common(1)[0][0]
        f.write('| %d | %.3f | %.3f | %d | %d | %.1f | %d (%s) | %s |\n' % (k, edges[k-1], edges[k], len(mem), len(cs), sum(s.min_depth() for _, s in mem)/len(mem), cid[dom], desc(dom),
                ', '.join('%s %d' % kv for kv in collections.Counter(POS[s.pos()] for _, s in mem).most_common())))
    f.write('| 0 | (undefined) | | %d | 1 | | %d (no relations) | %s |\n\n' % (len(classes[tuple([0]*19)]), cid[tuple([0]*19)], ', '.join('%s %d' % kv for kv in collections.Counter(POS[s.pos()] for s in classes[tuple([0]*19)]).most_common())))
    f.write('## Reading 2: attractor basins on the class graph\nNodes: %d classes. Edges join classes whose vectors differ by 1 in one coordinate (%d edges, %d connected components; degree min %d, median %d, max %d). Each class flows to its most populated neighbour while that is more populated than itself.\n\n' % (len(V), sum(deg)//2, ncomp, min(deg), sorted(deg)[len(deg)//2], max(deg)))
    f.write('| basin | attractor class | attractor vector | classes | synsets | pos mix | example synsets |\n|---|---|---|---|---|---|---|\n')
    for a in sorted(acls, key=lambda a: abasin[a]):
        mem = [s for v in acls[a] for s in classes[v]]
        f.write('| %d | %d | %s | %d | %d | %s | %s |\n' % (abasin[a], cid[a], desc(a), len(acls[a]), len(mem), ', '.join('%s %d' % kv for kv in collections.Counter(POS[s.pos()] for s in mem).most_common()), ', '.join(s.name() for s in classes[a][:3])))
json.dump({'synsets': len(syn), 'rows': n_rows, 'classes': len(V), 'density_valleys': valleys, 'attractor_basins': len(acls), 'components': ncomp,
           'class_graph_edges': sum(deg)//2}, open(os.path.join(HERE, 'summary.json'), 'w'), indent=1)
print('synsets', len(syn), 'rows', n_rows, 'classes', len(V), 'density basins', len(edges) - 1, 'attractor basins', len(acls), 'components', ncomp, 'edges', sum(deg)//2)
